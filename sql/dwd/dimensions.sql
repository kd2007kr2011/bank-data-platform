
-- ============================================================
-- D15 维度建模与星型模型
-- 数据库：bank_dev
-- Schema：dwd
--
-- 维度：
--   dim_region
--   dim_customer
--   dim_date
--
-- 事实：
--   fact_transaction
--   fact_loan_daily
--
-- 设计约定：
--   客户维度采用 SCD Type 1
--   交易事实粒度：一笔交易
--   贷款日事实粒度：一笔贷款 + 一个日期
--   金额使用 NUMERIC(18, 2)
-- ============================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS dwd;


-- ============================================================
-- 1. 地区维度
-- ============================================================

CREATE TABLE IF NOT EXISTS dwd.dim_region (

    region_key BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    region_name VARCHAR(100) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_dim_region_name
        UNIQUE (region_name),

    CONSTRAINT ck_dim_region_name
        CHECK (LENGTH(TRIM(region_name)) > 0)

);


-- ============================================================
-- 2. 客户维度
-- ============================================================

CREATE TABLE IF NOT EXISTS dwd.dim_customer (

    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    customer_id VARCHAR(64) NOT NULL,

    region_key BIGINT,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_dim_customer_id
        UNIQUE (customer_id),

    CONSTRAINT fk_dim_customer_region
        FOREIGN KEY (region_key)
        REFERENCES dwd.dim_region(region_key)

);

-- 当前版本：一个 customer_id 只有一行
-- 采用 SCD Type 1
-- 以后需要保留客户地区变更历史时，
-- 可以升级为 SCD Type 2。


-- ============================================================
-- 3. 日期维度
-- ============================================================

CREATE TABLE IF NOT EXISTS dwd.dim_date (

    date_key INTEGER PRIMARY KEY,

    full_date DATE NOT NULL,

    year_num INTEGER NOT NULL,

    quarter_num INTEGER NOT NULL,

    month_num INTEGER NOT NULL,

    day_num INTEGER NOT NULL,

    week_num INTEGER NOT NULL,

    day_of_week INTEGER NOT NULL,

    is_weekend BOOLEAN NOT NULL,

    CONSTRAINT uq_dim_date_full_date
        UNIQUE (full_date),

    CONSTRAINT ck_dim_date_quarter
        CHECK (quarter_num BETWEEN 1 AND 4),

    CONSTRAINT ck_dim_date_month
        CHECK (month_num BETWEEN 1 AND 12),

    CONSTRAINT ck_dim_date_day_of_week
        CHECK (day_of_week BETWEEN 1 AND 7)

);

-- 日期键使用 YYYYMMDD
-- 例如 2026-11-06 -> 20261106


-- ============================================================
-- 4. 交易事实表
-- ============================================================

CREATE TABLE IF NOT EXISTS dwd.fact_transaction (

    transaction_key BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    transaction_id VARCHAR(64) NOT NULL,

    customer_key BIGINT NOT NULL,

    region_key BIGINT,

    date_key INTEGER NOT NULL,

    account_id VARCHAR(64),

    transaction_time TIMESTAMPTZ NOT NULL,

    transaction_type VARCHAR(32) NOT NULL,

    transaction_status VARCHAR(32) NOT NULL,

    amount NUMERIC(18, 2) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_fact_transaction_id
        UNIQUE (transaction_id),

    CONSTRAINT fk_fact_transaction_customer
        FOREIGN KEY (customer_key)
        REFERENCES dwd.dim_customer(customer_key),

    CONSTRAINT fk_fact_transaction_region
        FOREIGN KEY (region_key)
        REFERENCES dwd.dim_region(region_key),

    CONSTRAINT fk_fact_transaction_date
        FOREIGN KEY (date_key)
        REFERENCES dwd.dim_date(date_key),

    CONSTRAINT ck_fact_transaction_amount
        CHECK (amount > 0),

    CONSTRAINT ck_fact_transaction_type
        CHECK (
            transaction_type IN (
                'DEPOSIT',
                'WITHDRAWAL',
                'TRANSFER'
            )
        ),

    CONSTRAINT ck_fact_transaction_status
        CHECK (
            transaction_status IN (
                'PENDING',
                'SUCCESS',
                'FAILED'
            )
        )

);


-- ============================================================
-- 5. 贷款日快照事实表
-- ============================================================

CREATE TABLE IF NOT EXISTS dwd.fact_loan_daily (

    loan_daily_key BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    loan_id VARCHAR(64) NOT NULL,

    customer_key BIGINT NOT NULL,

    region_key BIGINT,

    date_key INTEGER NOT NULL,


    total_disbursed NUMERIC(18, 2) NOT NULL
        DEFAULT 0,


    total_repaid_principal NUMERIC(18, 2) NOT NULL
        DEFAULT 0,


    outstanding_principal NUMERIC(18, 2) NOT NULL
        DEFAULT 0,

    overdue_days INTEGER NOT NULL
        DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_fact_loan_daily
        UNIQUE (loan_id, date_key),

    CONSTRAINT fk_fact_loan_customer
        FOREIGN KEY (customer_key)
        REFERENCES dwd.dim_customer(customer_key),

    CONSTRAINT fk_fact_loan_region
        FOREIGN KEY (region_key)
        REFERENCES dwd.dim_region(region_key),

    CONSTRAINT fk_fact_loan_date
        FOREIGN KEY (date_key)
        REFERENCES dwd.dim_date(date_key),

    CONSTRAINT ck_loan_disbursed
        CHECK (total_disbursed >= 0),

    CONSTRAINT ck_loan_repaid
        CHECK (total_repaid_principal >= 0),

    CONSTRAINT ck_loan_outstanding
        CHECK (outstanding_principal >= 0),

    CONSTRAINT ck_loan_overdue
        CHECK (overdue_days >= 0)

);


-- ============================================================
-- 6. 索引
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_dim_customer_region
ON dwd.dim_customer(region_key);

CREATE INDEX IF NOT EXISTS idx_fact_transaction_customer
ON dwd.fact_transaction(customer_key);

CREATE INDEX IF NOT EXISTS idx_fact_transaction_region_date
ON dwd.fact_transaction(region_key, date_key);

CREATE INDEX IF NOT EXISTS idx_fact_transaction_date
ON dwd.fact_transaction(date_key);

CREATE INDEX IF NOT EXISTS idx_fact_loan_customer
ON dwd.fact_loan_daily(customer_key);

CREATE INDEX IF NOT EXISTS idx_fact_loan_region_date
ON dwd.fact_loan_daily(region_key, date_key);

CREATE INDEX IF NOT EXISTS idx_fact_loan_date
ON dwd.fact_loan_daily(date_key);



-- ============================================================
-- D15 日期维度初始化
-- PostgreSQL 18
-- 生成 2020-01-01 至 2035-12-31
-- ============================================================


INSERT INTO dwd.dim_date (
    date_key,
    full_date,
    year_num,
    quarter_num,
    month_num,
    day_num,
    week_num,
    day_of_week,
    is_weekend
)
SELECT
    TO_CHAR(d, 'YYYYMMDD')::INTEGER,
    d::DATE,
    EXTRACT(YEAR FROM d)::INTEGER,
    EXTRACT(QUARTER FROM d)::INTEGER,
    EXTRACT(MONTH FROM d)::INTEGER,
    EXTRACT(DAY FROM d)::INTEGER,
    EXTRACT(WEEK FROM d)::INTEGER,
    EXTRACT(ISODOW FROM d)::INTEGER,
    EXTRACT(ISODOW FROM d) IN (6, 7)
FROM GENERATE_SERIES(
    DATE '2020-01-01',
    DATE '2035-12-31',
    INTERVAL '1 day'
) AS series(d)
ON CONFLICT (date_key) DO NOTHING;


-- ============================================================
-- 2. 检查初始化结果
-- ============================================================

SELECT
    COUNT(*) AS total_dates,
    MIN(full_date) AS start_date,
    MAX(full_date) AS end_date
FROM dwd.dim_date;

