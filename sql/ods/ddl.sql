-- D08 / PostgreSQL / 与 source 数据字典 V1.1 对齐
-- 只创建结构，不会自动加载数据。
CREATE SCHEMA IF NOT EXISTS ods;

CREATE TABLE IF NOT EXISTS ods.ods_transaction (
    ods_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 以下七列逐列对应 source.transactions 的全部字段
    transaction_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,
    amount NUMERIC(18,2) NOT NULL,
    transaction_status VARCHAR(20) NOT NULL,
    transaction_time TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    -- 以下三列由数据装载程序生成，不存在于 source.transactions
    batch_id VARCHAR(100) NOT NULL,
    load_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source_system VARCHAR(50) NOT NULL DEFAULT 'bank_core',
    CONSTRAINT uq_ods_transaction_batch UNIQUE (batch_id, transaction_id)
);

-- 保留源状态和金额内容：ODS 不新增源业务状态 CHECK 约束，也不建立到 Source 的 FK。
CREATE INDEX IF NOT EXISTS idx_ods_transaction_tid_load
    ON ods.ods_transaction (transaction_id, load_time DESC, ods_id DESC);
CREATE INDEX IF NOT EXISTS idx_ods_transaction_batch
    ON ods.ods_transaction (batch_id);

COMMENT ON TABLE ods.ods_transaction IS 'ODS 交易批次落地表：一行=一个批次的一笔源交易';
COMMENT ON COLUMN ods.ods_transaction.created_at IS 'Source 记录创建时间，来自 source.transactions.created_at';
COMMENT ON COLUMN ods.ods_transaction.load_time IS '仓库载入 ODS 的时间，不是交易时间';
