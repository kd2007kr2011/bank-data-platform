
-- =========================================================
-- 零售银行数据平台：源业务表
-- 文件：sql/source/001_schema.sql
-- 数据库：PostgreSQL
-- =========================================================

-- 1. 创建源业务数据 Schema
CREATE SCHEMA IF NOT EXISTS source;

-- 2. 客户表
CREATE TABLE IF NOT EXISTS source.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    customer_type VARCHAR(20) NOT NULL
        CHECK (customer_type IN ('INDIVIDUAL', 'BUSINESS')),
    customer_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (customer_status IN ('ACTIVE', 'INACTIVE', 'CLOSED')),
    open_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. 账户表
CREATE TABLE IF NOT EXISTS source.accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    account_type VARCHAR(20) NOT NULL
        CHECK (account_type IN ('SAVINGS', 'CURRENT', 'CREDIT')),
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    open_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_accounts_customer
        FOREIGN KEY (customer_id)
        REFERENCES source.customers(customer_id)
        ON DELETE RESTRICT
);

-- 4. 交易表
CREATE TABLE IF NOT EXISTS source.transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    transaction_type VARCHAR(20) NOT NULL
        CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    amount NUMERIC(18, 2) NOT NULL CHECK (amount > 0),
    transaction_status VARCHAR(20) NOT NULL
        CHECK (transaction_status IN (
            'PENDING', 'SUCCESS', 'FAILED', 'CANCELLED', 'REVERSED'
        )),
    transaction_time TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_transactions_account
        FOREIGN KEY (account_id)
        REFERENCES source.accounts(account_id)
        ON DELETE RESTRICT
);

-- 5. 贷款合同表
CREATE TABLE IF NOT EXISTS source.loans (
    loan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    contract_amount NUMERIC(18, 2) NOT NULL
        CHECK (contract_amount > 0),
    loan_status VARCHAR(20) NOT NULL
        CHECK (loan_status IN (
            'PENDING', 'ACTIVE', 'PAID_OFF', 'CANCELLED'
        )),
    contract_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_loans_customer
        FOREIGN KEY (customer_id)
        REFERENCES source.customers(customer_id)
        ON DELETE RESTRICT
);

-- 6. 实际放款表
CREATE TABLE IF NOT EXISTS source.loan_disbursements (
    disbursement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL,
    disbursement_amount NUMERIC(18, 2) NOT NULL
        CHECK (disbursement_amount > 0),
    disbursement_status VARCHAR(20) NOT NULL
        CHECK (disbursement_status IN (
            'PENDING', 'SUCCESS', 'FAILED', 'CANCELLED'
        )),
    disbursement_time TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_disbursements_loan
        FOREIGN KEY (loan_id)
        REFERENCES source.loans(loan_id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_disbursement_loan UNIQUE (disbursement_id, loan_id)
);

-- 7. 还款表
CREATE TABLE IF NOT EXISTS source.loan_repayments (
    repayment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL,
    principal_amount NUMERIC(18, 2) NOT NULL DEFAULT 0
        CHECK (principal_amount >= 0),
    interest_amount NUMERIC(18, 2) NOT NULL DEFAULT 0
        CHECK (interest_amount >= 0),
    repayment_status VARCHAR(20) NOT NULL
        CHECK (repayment_status IN (
            'PENDING', 'SUCCESS', 'FAILED', 'CANCELLED'
        )),
    repayment_time TIMESTAMPTZ NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_repayments_loan
        FOREIGN KEY (loan_id)
        REFERENCES source.loans(loan_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_repayment_amount
        CHECK (principal_amount + interest_amount > 0)
);

-- 8. 为常用关联和查询字段创建索引
CREATE INDEX IF NOT EXISTS idx_accounts_customer
    ON source.accounts(customer_id);

CREATE INDEX IF NOT EXISTS idx_transactions_account_time
    ON source.transactions(account_id, transaction_time);

CREATE INDEX IF NOT EXISTS idx_transactions_status_time
    ON source.transactions(transaction_status, transaction_time);

CREATE INDEX IF NOT EXISTS idx_loans_customer
    ON source.loans(customer_id);

CREATE INDEX IF NOT EXISTS idx_disbursements_loan_time
    ON source.loan_disbursements(loan_id, disbursement_time);

CREATE INDEX IF NOT EXISTS idx_repayments_loan_time
    ON source.loan_repayments(loan_id, repayment_time);
